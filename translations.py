# 🌐 LANGUAGE UTILITIES
# ============================================================

# RTL languages supported by common scripts. Only Arabic is currently
# included in LANGUAGES; the others are ready for future language additions.
RTL_LANGUAGES = {"ar", "fa", "he", "ur", "ps", "sd", "ug", "yi"}


def normalize_language(lang, default="en"):
    """Return a valid language code, falling back safely to English."""
    if not isinstance(lang, str):
        return default
    lang = lang.strip().lower().replace("_", "-").split("-", 1)[0]
    return lang if lang in LANGUAGES else default


def get_translation(lang, key, default=None):
    """Get a translated UI string with selected-language and English fallback."""
    lang = normalize_language(lang)
    language_text = TRANSLATIONS.get(lang, {})
    english_text = TRANSLATIONS.get("en", {})

    if key in language_text:
        return language_text[key]
    if key in english_text:
        return english_text[key]
    if default is not None:
        return default
    return key


def is_rtl(lang):
    """Return True when the selected language uses right-to-left layout."""
    return normalize_language(lang) in RTL_LANGUAGES


def get_language_name(lang):
    """Return the display name for a language code."""
    lang = normalize_language(lang)
    return LANGUAGES.get(lang, LANGUAGES["en"])


def get_language_options():
    """Return language display names in the same order as LANGUAGES."""
    return list(LANGUAGES.values())
